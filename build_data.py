def load_warning():
    out = {}
    for y in (2020, 2021, 2023, 2024, 2025):
        p = os.path.join(WORK, "warning_%d.csv" % y)
        if not os.path.exists(p):
            continue
        with open(p, encoding="utf-8-sig", newline="") as f:
            for row in csv.DictReader(f):
                name = (row.get("Journal") or "").strip()
                if not name:
                    continue
                reason = ""
                for k, v in row.items():
                    if k and k != "Journal" and v and v.strip():
                        reason = v.strip()
                        break
                rec = {"year": [y], "reason": reason}
                key = norm(name)
                if key in out:
                    out[key]["year"].append(y)
                    if reason and reason not in out[key]["reason"]:
                        out[key]["reason"] = out[key]["reason"] + "；" + reason
                else:
                    out[key] = rec
    for v in out.values():
        v["year"] = "/".join(str(x) for x in sorted(set(v["year"])))
    return out


def main():
    # 前置检查：数据源目录必须存在
    if not os.path.isdir(SRC):
        print("=" * 64)
        print("找不到数据源目录：%s" % SRC)
        print()
        print("本脚本需要以下原始索引文件来重建数据集：")
        print("  · CSSCI2025_索引.md         （CSSCI 2025-2026 来源版/扩展版）")
        print("  · CSCD2025_2026_提取.txt     （CSCD 2025-2026 核心库/扩展库）")
        print()
        print("请修改脚本顶部的 SRC 常量，或设置环境变量指向该目录：")
        print()
        print('    set SXFU_SRC_DIR=D:\\path\\to\\journal-data     （Windows CMD）')
        print('    export SXFU_SRC_DIR=/path/to/journal-data     （macOS / Linux）')
        print("=" * 64)
        sys.exit(1)

    print("[1/5] 载入 CSSCI ...")
    cssci_src, cssci_ext = load_cssci()
    print("      来源版 %d / 扩展版 %d" % (len(cssci_src), len(cssci_ext)))

    print("[2/5] 载入 CSCD ...")
    cscd_core, cscd_ext = load_cscd()
    print("      核心库 %d / 扩展库 %d" % (len(cscd_core), len(cscd_ext)))

    print("[3/5] 载入中科院分区 ...")
    cas_name, cas_issn = load_cas()
    print("      刊名 %d / ISSN %d" % (len(cas_name), len(cas_issn)))

    print("[4/5] 载入预警名单 ...")
    warn = load_warning()
    print("      %d 种" % len(warn))

    print("[5/5] 合并 ...")
    a1 = {norm(n): {"name": n, "issn": i} for n, i in A1_LIST}
    a2 = {norm(n): {"name": n, "issn": i} for n, i in A2_LIST}

    journals = {}

    def touch(name, **kw):
        k = norm(name)
        if not k:
            return None
        j = journals.setdefault(k, {"name": name})
        for kk, vv in kw.items():
            if vv not in (None, "", []):
                j[kk] = vv
        return j

    # CSSCI
    for k, v in cssci_src.items():
        touch(v["name"], cssci="source", subject=v.get("subject", ""))
    for k, v in cssci_ext.items():
        if k in journals and journals[k].get("cssci") == "source":
            continue
        touch(v["name"], cssci="ext", subject=v.get("subject", ""))
    # CSCD
    for k, v in cscd_core.items():
        touch(v["name"], cscd="core", issn=v.get("issn", ""))
    for k, v in cscd_ext.items():
        if k in journals and journals[k].get("cscd") == "core":
            continue
        touch(v["name"], cscd="ext", issn=v.get("issn", ""))

    # ---- 同刊合并（修 CSSCI / CSCD 命名不一致导致的漏判）----
    # 问题：CSSCI 用「地理学报(北京)」「管理学报(台湾)」区分**地域版本**，
    #       CSCD 却用不带括号的「地理学报」。两套数据源命名规则不同，
    #       导致合并时没对上 —— 结果是「地理学报」只有 CSCD 而丢了 CSSCI。
    # 规则：只合并**地域/版本后缀**，绝不合并**学科版**。
    #   合并：地理学报(北京)、地理学报(台湾) → 地理学报   （同一本刊的不同版本）
    #   不合并：北京工业大学学报(社会科学版) → 另一本刊   （社科版 ≠ 理工版）
    GEO_SUFFIX = re.compile(
        r"^(北京|台湾|湖北|上海|江苏|广东|四川|吉林|黑龙江|辽宁|山东|"
        r"陕西|甘肃|新疆|云南|贵州|重庆|天津|内蒙古|广西|海南|西藏|宁夏|青海|"
        r"Hong Kong|Taiwan)$"
    )
    SUBJECT_MARK = re.compile(
        r"(社会科学版|哲学社会科学版|人文社会科学版|教育版|医学版|自然科学版|"
        r"理学版|工学版|计算机版|地球科学版|地理科学版|中文版|英文版|"
        r"社会科学专刊|哲学社会科学版)"
    )
    merged = 0
    # 建立「无后缀刊名」→ 条目 的索引（仅收录确实无括号的）
    for key in list(journals.keys()):
        rec = journals[key]
        nm = rec["name"]
        m = re.search(r"[（(]([^）)]+)[）)]\s*$", nm)
        if not m:
            continue
        suffix = m.group(1).strip()
        # 只处理纯地域后缀，且必须是两个字/两个字母（避免误吞含学科名的长后缀）
        if not GEO_SUFFIX.match(suffix):
            continue
        if SUBJECT_MARK.search(suffix):
            continue
        base_name = nm[: m.start()].strip()
        base_key = norm(base_name)
        if base_key not in journals:
            # 没有无后缀条目，直接把名字改成无后缀形式
            rec["name"] = base_name
            new_key = base_key
            if new_key != key:
                del journals[key]
                journals[new_key] = rec
            continue
        # 存在无后缀条目 → 合并收录信息
        tgt = journals[base_key]
        for fld in ("cssci", "cscd", "issn", "cas", "univ", "univ985",
                    "univ985Social", "a3", "subject", "warning"):
            if rec.get(fld) and not tgt.get(fld):
                tgt[fld] = rec[fld]
        del journals[key]
        merged += 1
    if merged:
        print("      同刊合并 %d 条（地域版本后缀 → 主条目）" % merged)
    # 中科院
    for k, v in cas_name.items():
        touch(v["name"], cas=v, issn=v.get("issn", ""))
    # A1 / A2
    for k, v in a1.items():
        touch(v["name"], univ="A1")
    for k, v in a2.items():
        if k in a1:
            continue
        touch(v["name"], univ="A2")
    # 预警
    for k, v in warn.items():
        touch(k, warning=v)

    # 补 ISSN（从 CSCD / 中科院反向补）
    for k, j in journals.items():
        if not j.get("issn"):
            for src in (cscd_core, cscd_ext, cas_name):
                if k in src and src[k].get("issn"):
                    j["issn"] = src[k]["issn"]
                    break
        if not j.get("issn"):
            for n, v in a1.items():
                if n == k and v["issn"]:
                    j["issn"] = v["issn"]
            for n, v in a2.items():
                if n == k and v["issn"]:
                    j["issn"] = v["issn"]

    # 标注 985 关联
    for k, j in journals.items():
        nm = j["name"]
        for u in UNIV_985:
            if nm.startswith(u) and ("学报" in nm or "大学" in nm):
                j["univ985"] = u
                j["univ985Social"] = u in UNIV_985_SOCIAL
                break

    # 写入 A3 认定信息（显式白名单，主办单位已核实）
    a3_map = {}
    for nm, host, basis in A3_LIST:
        k = norm(nm)
        if k and k not in a3_map:
            a3_map[k] = {"host": host, "basis": basis}
    hit = 0
    for k, j in journals.items():
        if k in a3_map:
            j["a3"] = a3_map[k]
            hit += 1
    print("      A3 白名单 %d 条，命中数据集 %d 条" % (len(a3_map), hit))

    meta = {
        "name": "山财期刊标签插件",
        "version": "1.0.0",
        "built": "2026-10-02",
        "sources": {
            "cssci": "CSSCI 2025-2026 来源版 674 / 扩展版 261",
            "cscd": "CSCD 2025-2026 核心库 1110 / 扩展库 366",
            "cas": "中科院分区 2025 终版 21772 条（2026 年起停止更新）",
            "policy": "校级科研成果管理办法 附件1（A 级期刊目录）",
            "warning": "中科院国际期刊预警名单 2020-2025 累计",
        },
        "counts": {
            "total": len(journals),
            "cssciSource": len(cssci_src),
            "cssciExt": len(cssci_ext),
            "cscdCore": len(cscd_core),
            "cscdExt": len(cscd_ext),
            "cas": len(cas_name),
            "a1": len(a1),
            "a2": len(a2),
            "warning": len(warn),
        },
        "univ985": UNIV_985,
        "univ985Social": sorted(UNIV_985_SOCIAL),
        "a3count": len(a3_map),
        "notes": [
            "A3 认定采用显式白名单：仅当主办单位已核实（社科院/中科院/一级学会/国家部委/985及艺术体育外语顶尖院校学报）才判 A3。",
            "未列入白名单的 CSSCI来源/CSCD核心 期刊按 A4 处理，插件内会提示「A3 附条件待人工核实」。",
            "如需扩充 A3 名单，在 build_data.py 的 A3_LIST 中追加 (刊名, 主办单位, 认定依据) 后重跑构建即可。",
        ],
    }

    # ---- 分层输出：主表（判定必需，2.8MB）+ 分区明细（悬停详情，按需加载）----
    main = {}
    detail = {}
    for k, v in journals.items():
        nv = {"n": v["name"]}
        if "cssci" in v:
            nv["c"] = v["cssci"]          # source / ext
        if "cscd" in v:
            nv["d"] = v["cscd"]           # core / ext
        if "univ" in v:
            nv["s"] = v["univ"]          # A1 / A2
        if "issn" in v:
            nv["i"] = v["issn"]
        if "subject" in v:
            nv["j"] = v["subject"]
        if "warning" in v:
            nv["w"] = v["warning"]["year"]
        if "univ985" in v:
            nv["u"] = v["univ985"]
            nv["U"] = 1 if v.get("univ985Social") else 0
        if "a3" in v:
            nv["H"] = v["a3"]["host"]
            nv["B"] = v["a3"]["basis"]
        cas = v.get("cas")
        if cas:
            nv["z"] = cas["majorZone"]
            if cas["major"]:
                nv["M"] = cas["major"]
            if cas["top"]:
                nv["T"] = 1
            if cas["wos"]:
                nv["W"] = cas["wos"]
            if cas["review"]:
                nv["R"] = 1
            if cas["oa"] or cas["oaj"]:
                nv["O"] = 1
            if cas["minorZones"]:
                detail[k] = [[m["name"], m["zone"]] for m in cas["minorZones"]]
        if "warning" in v and v["warning"].get("reason"):
            nv["y"] = v["warning"]["reason"]
        main[k] = nv

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({"meta": meta, "journals": main}, f, ensure_ascii=False, separators=(",", ":"))

    detail_path = OUT.replace("journals.json", "cas_detail.json")
    with open(detail_path, "w", encoding="utf-8") as f:
        json.dump(detail, f, ensure_ascii=False, separators=(",", ":"))

    size = os.path.getsize(OUT)
    dsize = os.path.getsize(detail_path)
    print("\n✓ 写出 %s" % OUT)
    print("  主表 %d 条，%.2f MB" % (len(main), size / 1048576))
    print("✓ 写出 %s" % detail_path)
    print("  分区明细 %d 条，%.2f MB" % (len(detail), dsize / 1048576))


if __name__ == "__main__":
    main()
