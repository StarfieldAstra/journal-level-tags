def norm(s):
    """刊名归一化：去空白、统一括号、全角转半角、去副标题噪声、英文小写"""
    if not s:
        return ""
    s = str(s).strip()
    # 全角 -> 半角
    out = []
    for ch in s:
        code = ord(ch)
        if code == 0x3000:
            out.append(" ")
        elif 0xFF01 <= code <= 0xFF5E:
            out.append(chr(code - 0xFEE0))
        else:
            out.append(ch)
    s = "".join(out)
    # 去掉所有空白
    s = re.sub(r"\s+", "", s)
    # 统一括号为 ()
    s = s.replace("（", "(").replace("）", ")")
    s = s.replace("【", "(").replace("】", ")")
    s = s.replace("［", "(").replace("］", ")")
    s = s.replace("，", ",").replace("、", ",")
    # 去掉末尾的括号内容（副标题），如 "经济学(季刊)" -> "经济学"
    # 但保留必要信息：先记录原名，这里只做基础归一
    s = s.lower()
    return s


def norm_base(s):
    """更强归一化：进一步去掉副标题与常见后缀，用于模糊匹配"""
    s = norm(s)
    # 去掉末尾括号
    while s.endswith(")") and "(" in s:
        s = s[: s.rindex("(")].rstrip(",")
    # 去掉常见刊名后缀
    for suf in ("英文版", "英文", "中英文版", "专辑", "增刊", "专刊"):
        if s.endswith(suf):
            s = s[: -len(suf)]
    return s


# ---------------------------------------------------------------- 1. CSSCI
def load_cssci():
    path = os.path.join(SRC, "CSSCI2025_索引.md")
    source, ext = {}, {}
    section = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            if "## 一、CSSCI 来源期刊" in line:
                section = "source"
                continue
            if "## 二" in line and "扩展版" in line:
                section = "ext"
                continue
            if line.startswith("## "):
                section = None
                continue
            if section is None:
                continue
            m = re.match(r"^\|\s*(\d+)\s*\|\s*(.+?)\s*\|\s*(.*?)\s*\|\s*$", line)
            if not m:
                continue
            idx, name, subj = int(m.group(1)), m.group(2), m.group(3)
            if not name or name in ("期刊名", "---"):
                continue
            rec = {"name": name, "subject": subj, "no": idx}
            if section == "source":
                source[norm(name)] = rec
            else:
                ext[norm(name)] = rec
    return source, ext


# ---------------------------------------------------------------- 2. CSCD
def load_cscd():
    """CSCD PDF 提取文本为逐行结构：
        序号 / 期刊名 / ISSN / 库标识
    部分记录 ISSN 或库标识可能缺失，故用"行角色推断"而非固定位置。"""
    path = os.path.join(SRC, "CSCD2025_2026_提取.txt")
    lines = []
    with open(path, encoding="utf-8") as f:
        for raw in f:
            s = raw.strip()
            if not s or s.startswith("====="):
                continue
            lines.append(s)

    skip_exact = {
        "中国科学引文数据库来源期刊列表（2025—2026 年度）",
        "序号", "期刊名称", "ISSN", "库标识", "序号 期刊名称 ISSN 库标识",
    }
    issn_re = re.compile(r"^\d{4}-\d{3}[\dxX]$")
    no_re = re.compile(r"^(\d{1,4})\s+(.+)$")

    core, ext = {}, {}
    pending = None  # 待写入的记录 dict

    for s in lines:
        if s in skip_exact:
            pending = None
            continue
        if "核心库" in s and len(s) <= 6:
            if pending:
                core[norm(pending["name"])] = pending
            pending = None
            continue
        if "扩展库" in s and len(s) <= 6:
            if pending:
                ext[norm(pending["name"])] = pending
            pending = None
            continue
        if issn_re.match(s):
            if pending is not None:
                pending["issn"] = s.upper()
            continue
        m = no_re.match(s)
        if m:
            # "序号 刊名" 同行
            if pending:
                core[norm(pending["name"])] = pending
                pending = None
            name = m.group(2).strip()
            if name and name not in skip_exact:
                pending = {"name": name}
            continue
        # 纯刊名行
        if pending:
            core[norm(pending["name"])] = pending
            pending = None
        if s and s not in skip_exact and "ISSN" not in s:
            pending = {"name": s}
    if pending:
        core[norm(pending["name"])] = pending

    return core, ext


