def load_cas():
    path = os.path.join(WORK, "fq2025.csv")
    by_name, by_issn = {}, {}
    with open(path, encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            name = (row.get("Journal") or "").strip()
            if not name:
                continue
            issn_field = (row.get("ISSN/EISSN") or "").strip()
            issns = [x.strip().upper() for x in issn_field.split("/") if x.strip()]
            major = (row.get("大类") or "").strip()
            major_zone = (row.get("大类分区") or "").strip().split(" ")[0]
            minors = []
            for i in range(1, 7):
                mn = (row.get("小类%d" % i) or "").strip()
                mz = (row.get("小类%d分区" % i) or "").strip().split(" ")[0]
                if mn and mz:
                    minors.append({"name": mn, "zone": mz})
            wos = (row.get("Web of Science") or "").strip()
            rec = {
                "name": name,
                "issn": issns[0] if issns else "",
                "allIssn": issns,
                "major": major,
                "majorZone": major_zone,
                "top": (row.get("Top") or "").strip() == "是",
                "review": (row.get("Review") or "").strip() == "是",
                "oa": (row.get("Open Access") or "").strip() == "是",
                "oaj": (row.get("OA Journal Index（OAJ）") or "").strip() == "是",
                "wos": wos,
                "minorZones": minors,
                "year": 2025,
            }
            by_name.setdefault(norm(name), rec)
            for i in issns:
                if i:
                    by_issn.setdefault(i, rec)
    return by_name, by_issn


